"""Render the results from artifacts/results/*.json: no number is typed by hand.

- docs/RESULTS.md: every result (the full report, rewritten on each run).
- web/src/numbers.ts: the numbers the website shows.
- README.md: the short summary between the summary markers (headline macro-F1 with CIs, verified vs unverified
  precision, share of reports with an unverified label, search baseline nDCG@10), from the same results files.

Usage: python -m eval.report   (same as `make report`)
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from eval import ask_score, entry_point, retrieval, verifier_agent
from eval.labelling import _fmt, load_result, render_summary, summary_inputs
from radlabel.results import RESULTS_DIR

README = Path("README.md")
RESULTS = Path("docs/RESULTS.md")
WEB_NUMBERS = Path("web/src/numbers.ts")
SUMMARY_START = "<!-- summary:start: generated by `python -m eval.report`; do not edit -->"
SUMMARY_END = "<!-- summary:end -->"
RESULTS_HEADER = ("# RadLabel results\n\n_Generated from `artifacts/results/*.json` by `python -m eval.report` "
                  "(`make report`); do not edit. No number in this file is typed by hand. Design and protocol: "
                  "[SPEC.md](SPEC.md); decisions behind the numbers: [evaluation_notes.md](evaluation_notes.md)._\n\n")
PAIRED_NAMES = {
    "llm_only_minus_rule_baseline": "LLM only − rule baseline",
    "llm_verifier_minus_llm_only": "LLM + verifier − LLM only",
    "tier2_minus_llm_verifier": "LLM + verifier + Tier 2 − LLM + verifier",
    "tier2_minus_rule_baseline": "LLM + verifier + Tier 2 − rule baseline",
    "tier2_minus_llm_only": "LLM + verifier + Tier 2 − LLM only",
    "pipeline_clean_minus_llm_verifier": "run_pipeline, clean join − LLM + verifier",
    "pipeline_varied_minus_pipeline_clean": "run_pipeline, varied joins − clean join",
    "v2_minus_llm_only": "LLM + free checks + verifier agent (v2) − LLM only",
    "v2_minus_tier2": "v2 − LLM + verifier + Tier 2",
    "v2_minus_rule_baseline": "v2 − rule baseline",
}


# README summary wording for the best base search setup (SPEC §8.2)
SHORT_NAMES = {"dense_sentence": "base embeddings", "dense_sentence_filter": "base embeddings + negation filter",
               "rrf_plain": "base embeddings + BM25", "bm25": "BM25"}


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _review_limitation(t2: dict[str, Any] | None) -> list[str]:
    if t2 is None:
        return []
    rt = t2["routing"]
    dist = rt["tier_distribution"]
    return [f"- v1 sent {_pct(dist.get('review', 0) / sum(dist.values()))} of reports to human review (hedged "
            f"{_pct(rt['review_rate_hedged'])}, clear {_pct(rt['review_rate_clear'])}); v2 replaced the review queue "
            "with the verifier agent and an `unverified` mark (see the verifier agent section, M7)."]


def _reading(paired: dict[str, Any], t2: dict[str, Any] | None) -> list[str]:
    """Plain-language reading of the guardrail comparisons; the wording follows the paired test, not a claim."""
    v, t, f = (paired.get(k) for k in ("llm_verifier_minus_llm_only", "tier2_minus_llm_verifier",
                                        "tier2_minus_llm_only"))
    if t2 is None or v is None or t is None or f is None:
        return []
    if not f["ci_excludes_zero"]:
        verdict = (f"the full pipeline **matches** LLM-only macro-F1 (difference {_fmt(f)}; the 95% CI includes 0). "
                   "The guardrails do not improve F1 over LLM only")
    elif f["value"] > 0:
        verdict = f"the full pipeline is **above** LLM only by {_fmt(f)} (95% CI excludes 0)"
    else:
        verdict = f"the full pipeline is **below** LLM only by {_fmt(f)} (95% CI excludes 0)"
    ch = t2["tier2_label_changes"]["all_211"]["total"]
    dist = t2["routing"]["tier_distribution"]
    return ["", f"**Reading (v1).** The verifier's hedge downgrade costs {abs(v['value']):.3f} macro-F1 and Tier 2 "
            f"recovers {t['value']:.3f}, so {verdict}. What the v1 guardrails added is label-level correction (Tier 2: "
            f"{ch.get('wrong_to_right', 0)} labels wrong → right vs {ch.get('right_to_wrong', 0)} right → wrong) and "
            f"routing of uncertain cases to human review ({_pct(dist.get('review', 0) / sum(dist.values()))} of "
            "reports)."]


def _heldout_limitation() -> list[str]:
    ft = load_result("retrieval_finetuned")
    if ft is None:
        return []
    d = ft["paired"]["ft_sentence_minus_dense_sentence"]["heldout_label"]["ndcg"]
    if d["ci_excludes_zero"] and d["value"] > 0:
        return []
    return [f"- Embedding fine-tuning helps the findings it was trained on and their unseen wordings, not unseen "
            f"findings: no gain on the three held-out findings (nDCG@10 change {_fmt(d)})."]


def _v2_claim() -> str:
    p = load_result("labelling_v2_paired_diffs")
    if p is None or not (p["v2_minus_tier2"]["lo"] > 0 and p["v2_minus_llm_only"]["lo"] > 0):
        return ""
    return ("; the v2 pipeline (LLM + free checks + verifier agent) improves over v1 (LLM + verifier + Tier 2) and "
            "over LLM only; verified labels are far more accurate than unverified ones")


def render() -> str:
    systems, paired = summary_inputs()
    head = systems["LLM + verifier"]
    run = head["run"]  # Tier 1 run stats (incl. Tier 0)
    t2: dict[str, Any] | None = load_result("labelling_llm_verifier_tier2")
    lines = [
        "**Claim scope.** Supported, on this dataset under this evaluation protocol: the LLM labelling pipeline "
        "improves over the implemented rule baseline" + _v2_claim() + ". Not supported: clinical reliability; "
        "\"verified\" means checked to faithfully reflect the report text, not that the report or the coding is "
        "right.", "",
        "Limitations that bound these numbers (details in [SPEC §11](SPEC.md#11-limitations)):",
        "- One institution (Indiana University, Open-i); reports from around 2013.",
        "- Expert codes are positive-only.",
        f"- Hedged reports ({head['n_hedged_excluded']} unique texts) are excluded from the headline metrics.",
        "- The mapping from MeSH codes to the 13 labels is lossy (results under mapping v1 and strict).",
        "- Rare labels have small support, hence wide CIs.",
        f"- {run['content_filtered']} reports refused by the Azure content filter are scored with the rule baseline's "
        "labels.",
        "- The ground truth misses some clearly stated findings, so scores are a lower bound.",
        "- Labels describe the report text, not the images.",
        *_heldout_limitation(),
        *_review_limitation(t2), "",
        "## Labelling (SPEC §8.1)", "",
        render_summary(systems, paired, standalone=False).rstrip(), "",
        "Per-label tables: `artifacts/tables/labelling_*.md`.", "",
        "## Paired differences", "",
        "Headline macro-F1 (9 labels, v1), same out-of-fold reports and the same 1,000 cluster resamples for both "
        "systems.", "",
        "| Comparison | Difference (95% CI) | CI excludes 0 |", "|---|---|---|",
    ]
    lines += [f"| {PAIRED_NAMES.get(k, k)} | {_fmt(d)} | {'yes' if d['ci_excludes_zero'] else 'no'} |"
              for k, d in paired.items()]
    lines += _reading(paired, t2)
    lines += ["", "## Pipeline (v1)", "",
              f"- Tier 1: {run['n_reports']:,} unique report texts labelled by {', '.join(run['models_returned'])} "
              f"(prompt `{run['prompt_version']}`, temperature 0); invalid outputs {run['invalid_outputs']}; "
              f"content-filtered {run['content_filtered']}.",
              f"- Tier 0: {run['tier0']['oof_hits']} out-of-fold matches (exact duplicates share a fold).",
              f"- Verifier FAIL → Tier 2: {run['tier2_reports']} reports ({_pct(run['report_fail_rate'])})."]
    if t2 is not None:
        st, rt, ch = t2["tier2"], t2["routing"], t2["tier2_label_changes"]["all_211"]["total"]
        dist = rt["tier_distribution"]
        n = sum(dist.values())
        lines += [
            f"- Tier 2 repair agent ({', '.join(st['models_returned'])}, prompt `{st['prompt_version']}`): "
            f"fix accepted after re-verification for {st['accepted']} of {st['tier2_reports']} "
            f"({_pct(st['repair_success_rate'])}); "
            f"mean tool calls {st['mean_tool_calls']:.2f}; labels changed {ch.get('status_changed', 0)}: "
            f"wrong → right {ch.get('wrong_to_right', 0)}, right → wrong {ch.get('right_to_wrong', 0)} "
            f"(present = positive vs expert codes).",
            f"- Routing: Tier 1 accepted {dist.get('tier1_accepted', 0):,}, Tier 2 repaired "
            f"{dist.get('tier2_repaired', 0)}, review {dist.get('review', 0)} ({_pct(dist.get('review', 0) / n)}).",
            f"- Review rate: hedged {_pct(rt['review_rate_hedged'])} vs clear {_pct(rt['review_rate_clear'])}. "
            f"Escalation precision (Tier 1 labels disagree with the expert codes): Tier 2 "
            f"{_pct(rt['escalation_precision_tier2'])}, review {_pct(rt['escalation_precision_review'])}, base rate "
            f"{_pct(rt['tier1_disagreement_base_rate'])}.",
            f"- LLM spend: Tier 2 calls ${st['tier2_cost_usd']:.2f}. Reruns are served from the cache at $0."]
    else:
        lines.append(f"- LLM spend, all calls so far (from the cost ledger): ${run['llm_spend_total_usd']:.2f}.")
    m6 = load_result("pipeline_m6")
    if m6 is not None:
        lines += ["", "## Through the entry point (M6)", "",
                  "Labels produced by `run_pipeline(raw_text)` (parse → tag → verifier), as an upload would be. "
                  "Without headers the parser can't separate sections, so the whole text, including the indication, "
                  "is read as Findings.", "",
                  entry_point.render(m6, load_result("labelling_m6_paired_diffs") or {}, standalone=False).rstrip()]
    v2 = load_result("labelling_llm_agent_v2")
    if v2 is not None:
        pf = RESULTS_DIR / "labelling_v2_paired_diffs.json"
        decision = json.loads(pf.read_text(encoding="utf-8"))["provenance"].get("decision") if pf.exists() else None
        v2p = load_result("labelling_v2_paired_diffs") or {}
        an = load_result("verifier_agent_analysis")
        lines += ["", "## Verifier agent (M7, v2)", "",
                  verifier_agent.render_reading(v2, v2p, an, load_result("verifier_escalation")).rstrip(), "",
                  verifier_agent.render_full(v2, v2p, decision).rstrip()]
        if an is not None:
            lines += ["", "### Per label, suggested labels and the normal-check ablation (after M7)", "",
                      verifier_agent.render_analysis(an).rstrip()]
        bf = load_result("labelling_v2_borderline_fix")
        if bf is not None:
            lines += ["", "### Final borderline rule (after M10a)", "", verifier_agent.render_borderline(bf).rstrip()]
    esc = load_result("verifier_escalation")
    if esc is not None:
        lines += ["", "### Escalation before any agent call, and the dev slice", "",
                  verifier_agent.render(esc, load_result("verifier_agent_dev")).rstrip()]
    ret, ib = load_result("retrieval_base"), load_result("index_build")
    if ret is not None:
        lines += ["", "## Retrieval (M8, SPEC §8.2): base models", ""]
        if ib is not None:
            pg, ok = ib["postgres_rows"], "yes" if ib["check_payload_keys_whitelisted"] else "NO"
            lines += [f"Index from the M7 v2 outputs (predicted labels only): Postgres {pg['reports']:,} "
                      f"reports and {pg['labels']:,} labels; Qdrant {ib['report_points']:,} report and "
                      f"{ib['sentence_points']:,} sentence points ({ib['embedding_model']}). Checks on "
                      f"the stored points: payload keys whitelisted {ok}; indication text in a point "
                      f"{ib['check_indication_found_in_points']} of {ib['check_indications_tested']:,} tested "
                      f"({ib['indication_phrase_also_in_own_findings_or_impression']} reports repeat the "
                      "indication's words in their own Findings/Impression).", ""]
        lines += [retrieval.reading(ret), "",
                  "Per fold, each fold's reports indexed alone; pooled over (query, fold) pairs with 95% bootstrap "
                  "CIs; spec frozen before the run (`eval/queries/retrieval_v1.yaml`).", "",
                  retrieval.render(ret).rstrip()]
    ft = load_result("retrieval_finetuned")
    if ft is not None:
        lines += ["", "## Embedding fine-tuning (M9, SPEC §8.2)", "",
                  retrieval.render_finetuned(ft, load_result("embedding_training"),
                                             load_result("embedding_serving_model")).rstrip(), "",
                  "### All rows, fine-tuning run", "", retrieval.render(ft).rstrip()]
    ask = load_result("ask_eval")
    if ask is not None:
        lines += ["", "## Ask evaluation (M10b, SPEC §8.3)", "", ask_score.render(ask).rstrip()]
    return "\n".join(lines) + "\n"


def summary() -> str:
    """README summary block: the same headline numbers as docs/RESULTS.md, from the results files."""
    systems, _ = summary_inputs()
    v2 = load_result("labelling_llm_agent_v2")
    ret = load_result("retrieval_base")
    if v2 is None or ret is None:
        raise SystemExit("the README summary needs the M7 and M8 results")
    g, r = v2["verification_groups"], v2["rates"]
    best = ret["best_base"]["variant"] if "best_base" in ret else max(
        ret["variants"], key=lambda v: ret["variants"][v]["all"]["ndcg"]["value"])
    b = ret["variants"][best]["all"]
    return "\n".join([
        "| | Macro-F1, 9 headline labels |", "|---|---|",
        f"| Keyword rules (baseline) | {_fmt(systems['Rule baseline']['v1']['macro_f1_headline'])} |",
        f"| LLM tagger only | {_fmt(systems['LLM only']['v1']['macro_f1_headline'])} |",
        f"| **Full pipeline (tagger + checks + verifier agent)** | **{_fmt(v2['v1']['macro_f1_headline'])}** |", "",
        f"- Verified labels are right far more often than unverified ones: precision "
        f"**{g['verified_or_verified_rules']['precision']:.3f} vs {g['unverified']['precision']:.3f}**.",
        f"- Only **{_pct(r['unverified_report_rate'])}** of reports end with any unverified label.",
        search_line(best, b), *([ask_score.summary_line(ask)] if (ask := load_result("ask_eval")) else [])]) + "\n"


def search_line(best: str, b: dict[str, Any]) -> str:
    ft = load_result("retrieval_finetuned")
    if ft is None:
        return (f"- Search baseline ({SHORT_NAMES.get(best, retrieval.NAMES[best])}, nDCG@10 over {b['n_pairs']} "
                f"query–fold pairs): **{b['ndcg']['value']:.3f}**. Negation-aware fine-tuning is in progress.")
    v, u = ft["variants"], ft["use_rule"]
    f, base = v["ft_sentence"]["all"], v["dense_sentence"]["all"]
    return (f"- Search (nDCG@10, {b['n_pairs']} query–fold pairs): base embeddings {_fmt(base['ndcg'])} → "
            f"negation-aware fine-tuned **{_fmt(f['ndcg'])}**; reports that only mention the finding as negated drop "
            f"from {_pct(base['contamination']['value'])} to {_pct(f['contamination']['value'])} of the top 10. "
            + ("The fine-tuned model is used for search." if u["use_finetuned_for_search"]
               else "The base model stays in use (pre-committed rule not met)."))


def web_numbers() -> str:
    """web/src/numbers.ts: every number the website shows, from the same results files as docs/RESULTS.md."""
    from radlabel.config import Settings

    v2, ft, card = load_result("labelling_llm_agent_v2"), load_result("retrieval_finetuned"), load_result("data_card")
    if v2 is None or ft is None or card is None:
        raise SystemExit("the website numbers need the data card, M7 and M9 results")
    g, v = v2["verification_groups"], ft["variants"]
    base, f = v["dense_sentence"]["all"], v["ft_sentence"]["all"]
    rows = [
        ("MACRO_F1", f"'{v2['v1']['macro_f1_headline']['value']:.3f}'", "headline macro-F1, 9 labels (v1), v2"),
        ("REPORTS_TESTED", f"'{card['unique_texts']:,}'", "unique report texts labelled"),
        ("VERIFIED_RIGHT", f"{round(100 * g['verified_or_verified_rules']['precision'])}",
         "% precision of verified + verified_rules labels"),
        ("UNVERIFIED_RIGHT", f"{round(100 * g['unverified']['precision'])}", "% precision of unverified labels"),
        ("SEARCH_NDCG_BASE", f"'{base['ndcg']['value']:.3f}'", "search nDCG@10, base embeddings"),
        ("SEARCH_NDCG_FINETUNED", f"'{f['ndcg']['value']:.3f}'", "search nDCG@10, negation-aware fine-tuned (in use)"),
        ("NEGATED_TOP10_BASE", f"'{100 * base['contamination']['value']:.1f}'",
         "% of the top 10 that only mention the finding as negated, base"),
        ("NEGATED_TOP10_FINETUNED", f"'{100 * f['contamination']['value']:.1f}'", "same, fine-tuned"),
        ("MAX_FILES", str(Settings.model_fields["web_max_reports"].default), "reports per session (WEB_MAX_REPORTS)"),
    ]
    return ("// Generated by `python -m eval.report` from artifacts/results/*.json (same numbers as docs/RESULTS.md);\n"
            "// do not edit.\n" + "".join(f"export const {k} = {val} // {c}\n" for k, val, c in rows))


def main() -> None:
    RESULTS.write_text(RESULTS_HEADER + render(), encoding="utf-8", newline="\n")
    WEB_NUMBERS.write_text(web_numbers(), encoding="utf-8", newline="\n")
    text = README.read_text(encoding="utf-8")
    a, b = text.index(SUMMARY_START) + len(SUMMARY_START), text.index(SUMMARY_END)
    README.write_text(text[:a] + "\n\n" + summary() + "\n" + text[b:], encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
