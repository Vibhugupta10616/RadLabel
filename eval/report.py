"""Render README §10 (Results) from artifacts/results/*.json: no number in §10 is typed by hand.

Replaces the text between the two results markers in README.md.

Usage: python -m eval.report   (same as `make report`)
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from eval import entry_point, verifier_agent
from eval.labelling import _fmt, load_result, render_summary, summary_inputs
from radlabel.results import RESULTS_DIR

README = Path("README.md")
START = "<!-- results:start: generated by `python -m eval.report` from artifacts/results/*.json; do not edit -->"
END = "<!-- results:end -->"
PAIRED_NAMES = {
    "llm_only_minus_rule_baseline": "LLM only − rule baseline",
    "llm_verifier_minus_llm_only": "LLM + verifier − LLM only",
    "tier2_minus_llm_verifier": "LLM + verifier + Tier 2 − LLM + verifier",
    "tier2_minus_rule_baseline": "LLM + verifier + Tier 2 − rule baseline",
    "tier2_minus_llm_only": "LLM + verifier + Tier 2 − LLM only",
    "pipeline_clean_minus_llm_verifier": "run_pipeline, clean join − LLM + verifier",
    "pipeline_varied_minus_pipeline_clean": "run_pipeline, varied joins − clean join",
    "v2_minus_llm_only": "LLM + free checks + verifier agent (v2) − LLM only",
    "v2_minus_tier2": "v2 − LLM + verifier + Tier 2",
    "v2_minus_rule_baseline": "v2 − rule baseline",
}


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _review_limitation(t2: dict[str, Any] | None) -> list[str]:
    if t2 is None:
        return []
    rt = t2["routing"]
    dist = rt["tier_distribution"]
    return [f"- Review volume is {_pct(dist.get('review', 0) / sum(dist.values()))} of reports (hedged "
            f"{_pct(rt['review_rate_hedged'])}, clear {_pct(rt['review_rate_clear'])}), too high for production use; "
            "reducing it is future work."]


def _reading(paired: dict[str, Any], t2: dict[str, Any] | None) -> list[str]:
    """Plain-language reading of the guardrail comparisons; the wording follows the paired test, not a claim."""
    v, t, f = (paired.get(k) for k in ("llm_verifier_minus_llm_only", "tier2_minus_llm_verifier",
                                        "tier2_minus_llm_only"))
    if t2 is None or v is None or t is None or f is None:
        return []
    if not f["ci_excludes_zero"]:
        verdict = (f"the full pipeline **matches** LLM-only macro-F1 (difference {_fmt(f)}; the 95% CI includes 0). "
                   "The guardrails do not improve F1 over LLM only")
    elif f["value"] > 0:
        verdict = f"the full pipeline is **above** LLM only by {_fmt(f)} (95% CI excludes 0)"
    else:
        verdict = f"the full pipeline is **below** LLM only by {_fmt(f)} (95% CI excludes 0)"
    ch = t2["tier2_label_changes"]["all_211"]["total"]
    dist = t2["routing"]["tier_distribution"]
    return ["", f"**Reading.** The verifier's hedge downgrade costs {abs(v['value']):.3f} macro-F1 and Tier 2 recovers "
            f"{t['value']:.3f}, so {verdict}. What the guardrails add is label-level correction (Tier 2: "
            f"{ch.get('wrong_to_right', 0)} labels wrong → right vs {ch.get('right_to_wrong', 0)} right → wrong) and "
            f"routing of uncertain cases to human review ({_pct(dist.get('review', 0) / sum(dist.values()))} of "
            "reports)."]


def render() -> str:
    systems, paired = summary_inputs()
    head = systems["LLM + verifier"]
    run = head["run"]  # Tier 1 run stats (incl. Tier 0)
    t2: dict[str, Any] | None = load_result("labelling_llm_verifier_tier2")
    lines = [
        "**Claim scope.** Supported: the LLM labelling pipeline improves over the implemented rule baseline on this "
        "dataset under this evaluation protocol. Not supported: clinical reliability.", "",
        "Limitations that bound these numbers (details in §11):",
        "- One institution (Indiana University, Open-i); reports from around 2013.",
        "- Expert codes are positive-only.",
        f"- Hedged reports ({head['n_hedged_excluded']} unique texts) are excluded from the headline metrics.",
        "- The mapping from MeSH codes to the 13 labels is lossy (results under mapping v1 and strict).",
        "- Rare labels have small support, hence wide CIs.",
        f"- {run['content_filtered']} reports refused by the Azure content filter are scored with the rule baseline's "
        "labels.",
        "- The ground truth misses some clearly stated findings, so scores are a lower bound.",
        "- Labels describe the report text, not the images.",
        *_review_limitation(t2), "",
        "### Labelling (§8.1)", "",
        render_summary(systems, paired, standalone=False).rstrip(), "",
        "Per-label tables: `artifacts/tables/labelling_*.md`.", "",
        "### Paired differences", "",
        "Headline macro-F1 (9 labels, v1), same out-of-fold reports and the same 1,000 cluster resamples for both "
        "systems.", "",
        "| Comparison | Difference (95% CI) | CI excludes 0 |", "|---|---|---|",
    ]
    lines += [f"| {PAIRED_NAMES.get(k, k)} | {_fmt(d)} | {'yes' if d['ci_excludes_zero'] else 'no'} |"
              for k, d in paired.items()]
    lines += _reading(paired, t2)
    lines += ["", "### Pipeline", "",
              f"- Tier 1: {run['n_reports']:,} unique report texts labelled by {', '.join(run['models_returned'])} "
              f"(prompt `{run['prompt_version']}`, temperature 0); invalid outputs {run['invalid_outputs']}; "
              f"content-filtered {run['content_filtered']}.",
              f"- Tier 0: {run['tier0']['oof_hits']} out-of-fold matches (exact duplicates share a fold).",
              f"- Verifier FAIL → Tier 2: {run['tier2_reports']} reports ({_pct(run['report_fail_rate'])})."]
    if t2 is not None:
        st, rt, ch = t2["tier2"], t2["routing"], t2["tier2_label_changes"]["all_211"]["total"]
        dist = rt["tier_distribution"]
        n = sum(dist.values())
        lines += [
            f"- Tier 2 repair agent ({', '.join(st['models_returned'])}, prompt `{st['prompt_version']}`): "
            f"fix accepted after re-verification for {st['accepted']} of {st['tier2_reports']} "
            f"({_pct(st['repair_success_rate'])}); "
            f"mean tool calls {st['mean_tool_calls']:.2f}; labels changed {ch.get('status_changed', 0)}: "
            f"wrong → right {ch.get('wrong_to_right', 0)}, right → wrong {ch.get('right_to_wrong', 0)} "
            f"(present = positive vs expert codes).",
            f"- Routing: Tier 1 accepted {dist.get('tier1_accepted', 0):,}, Tier 2 repaired "
            f"{dist.get('tier2_repaired', 0)}, review {dist.get('review', 0)} ({_pct(dist.get('review', 0) / n)}).",
            f"- Review rate: hedged {_pct(rt['review_rate_hedged'])} vs clear {_pct(rt['review_rate_clear'])}. "
            f"Escalation precision (Tier 1 labels disagree with the expert codes): Tier 2 "
            f"{_pct(rt['escalation_precision_tier2'])}, review {_pct(rt['escalation_precision_review'])}, base rate "
            f"{_pct(rt['tier1_disagreement_base_rate'])}.",
            f"- LLM spend: Tier 2 calls ${st['tier2_cost_usd']:.2f}. Reruns are served from the cache at $0."]
    else:
        lines.append(f"- LLM spend, all calls so far (from the cost ledger): ${run['llm_spend_total_usd']:.2f}.")
    m6 = load_result("pipeline_m6")
    if m6 is not None:
        lines += ["", "### Through the entry point (M6)", "",
                  "Labels produced by `run_pipeline(raw_text)` (parse → tag → verifier), as an upload would be. "
                  "Without headers the parser can't separate sections, so the whole text, including the indication, "
                  "is read as Findings.", "",
                  entry_point.render(m6, load_result("labelling_m6_paired_diffs") or {}, standalone=False).rstrip()]
    v2 = load_result("labelling_llm_agent_v2")
    if v2 is not None:
        pf = RESULTS_DIR / "labelling_v2_paired_diffs.json"
        decision = json.loads(pf.read_text(encoding="utf-8"))["provenance"].get("decision") if pf.exists() else None
        lines += ["", "### Verifier agent (M7, v2)", "",
                  verifier_agent.render_full(v2, load_result("labelling_v2_paired_diffs") or {}, decision).rstrip()]
    esc = load_result("verifier_escalation")
    if esc is not None:
        lines += ["", "#### Escalation before any agent call, and the dev slice", "",
                  verifier_agent.render(esc, load_result("verifier_agent_dev")).rstrip()]
    return "\n".join(lines) + "\n"


def main() -> None:
    text = README.read_text(encoding="utf-8")
    a, b = text.index(START) + len(START), text.index(END)
    README.write_text(text[:a] + "\n\n" + render() + "\n" + text[b:], encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
